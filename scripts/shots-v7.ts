// Swarm agent cards (red + green) and the minimal Dashboard header -> shots/v7/.
import { chromium } from "playwright-core";
import { mkdirSync } from "node:fs";
const url = process.argv[2] ?? "http://localhost:5177";
mkdirSync("shots/v7", { recursive: true });
const b = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", args: ["--force-dark-mode"] });
const ctx = await b.newContext({ viewport: { width: 1480, height: 940 }, deviceScaleFactor: 2, colorScheme: "dark" });
const p = await ctx.newPage();
const errs: string[] = [];
p.on("pageerror", (e) => errs.push(String(e)));
p.on("response", (r) => r.status() >= 400 && errs.push(`${r.status()} ${r.url()}`));
await p.goto(`${url}/app`);
await p.getByTestId("swarm-8").click();
await p.getByTestId("run").click();
await p.waitForSelector('[data-testid="run"][disabled]', { timeout: 10_000 }).catch(() => {});
await p.waitForSelector('[data-testid="run"]:not([disabled])', { timeout: 300_000 });
await p.getByTestId("nav-swarm").click();
await p.mouse.move(900, 900);
await p.waitForSelector('[data-testid="tile-S3"].bad', { timeout: 120_000 });
await p.getByTestId("tile-S3").click();
await p.waitForSelector('[data-testid="agentcard-S3"]');
console.log("red card:", (await p.getByTestId("agentcard-S3").innerText()).replace(/\s+/g, " "), "| url still swarm:", p.url().includes("#swarm"));
await p.waitForTimeout(300);
await p.screenshot({ path: "shots/v7/swarm-card-red.png", clip: { x: 0, y: 0, width: 1480, height: 620 } });
await p.keyboard.press("Escape");
console.log("closed on Esc:", (await p.getByTestId("agentcard-S3").count()) === 0);
await p.getByTestId("tile-S2").click();
await p.waitForSelector('[data-testid="agentcard-S2"]');
console.log("green card:", (await p.getByTestId("agentcard-S2").innerText()).replace(/\s+/g, " "));
await p.waitForTimeout(300);
await p.screenshot({ path: "shots/v7/swarm-card-green.png", clip: { x: 0, y: 0, width: 1480, height: 620 } });
await p.mouse.click(1200, 880);
console.log("closed on outside click:", (await p.getByTestId("agentcard-S2").count()) === 0);
await p.getByTestId("tile-S3").click();
await p.getByTestId("details-S3").click();
await p.waitForSelector('[data-testid="incident-sentence"]', { timeout: 60_000 });
console.log("details S3 -> dashboard + what went wrong:", (await p.getByTestId("incident-sentence").innerText()).trim(), "| to =", await p.getByTestId("to").inputValue());
await p.keyboard.press("Escape");
await p.waitForTimeout(400);
await p.screenshot({ path: "shots/v7/dashboard-header.png", clip: { x: 0, y: 0, width: 1480, height: 340 } });
console.log("pixel art on dashboard:", await p.locator("main .page-art").count());
await p.getByTestId("nav-swarm").click();
await p.getByTestId("tile-S2").click();
await p.getByTestId("details-S2").click();
await p.waitForSelector('[data-testid="report-summary"]', { timeout: 60_000 });
console.log("details S2 -> dashboard, incident open:", await p.getByTestId("incident").count(), "| to =", await p.getByTestId("to").inputValue());
console.log(errs.length ? errs : "no page errors");
await b.close();
